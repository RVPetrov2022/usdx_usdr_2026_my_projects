// АРУ (AGC) — Без переполнения и без жесткого уничтожения бит
//#######################################################################
inline int16_t process_agc(int16_t in) {
  static bool small = true;
  int32_t out_long;

  // Оставляем родную логику uSDX для centiGain, но убираем сдвиг слабого входа (in >> 3)
  if (centiGain >= 128) {
    out_long = ((int32_t)(centiGain >> 5) * in) >> 2; 
  } else {
    // Вместо (centiGain >> 2) * (in >> 3) >> 2 делаем эквивалентное по громкости,
    // но безопасное для младших бит умножение:
    out_long = ((int32_t)(centiGain >> 2) * in) >> 5;
  }

  // Защита от переполнения (клиппинга), чтобы не было грозового рева
  if (out_long > 32767)  out_long = 32767;
  if (out_long < -32768) out_long = -32768;
  int16_t out = (int16_t)out_long;

  // Родной неизмененный автомат АРУ uSDX
  if (HI(abs(out)) > HI(1536)) {
    centiGain -= (centiGain >> 4);  
  } else {
    if (HI(abs(out)) > HI(1024))
      small = false;
    if (--decayCount == 0) {  
      if (small) {            
        if (centiGain < (INT16_MAX - (INT16_MAX >> 4)))
          centiGain += (centiGain >> 4);
        else
          centiGain = INT16_MAX;
      }
      decayCount = DECAY_FACTOR;
      small = true;
    }
  }
  return out;
}

