inline int16_t slow_dsp(int16_t ac) {
  static uint8_t absavg256cnt;
  if (!(absavg256cnt--)) {
    _absavg256 = absavg256;
    absavg256 = 0;
  } else absavg256 += abs(ac);

  //#####################################################################################
  // 1. АМ-детектор с сохранением полной чувствительности (Без слепоты АРУ)
  //#####################################################################################
  if (mode == AM) {
    // Используем честный magn(), чтобы восстановить разрядность сигналов I и Q после biquad-фильтра
    int32_t am_envelope = magn(i, q); 

    // Классический медленный накопитель несущей Гвидо
    static int32_t am_dc;
    am_dc += (am_envelope - am_dc) / 512; 

    // Вычитаем несущую частоту
    int32_t am_audio = am_envelope - am_dc; 
    
    // Поднимаем чувствительность мелкой модуляции ровно в 16 раз (заводская норма)
    ac = am_audio << 4;

    // Лимитер под ШИМ-выход
    if (ac > 2047)  ac = 2047;
    if (ac < -2047) ac = -2047;

    // Мягкое DC-отсечение гула. Делитель /4 не дает сигналу утонуть в шумах
    {
      static int16_t dc;
      dc += (ac - dc) / 4; 
      ac = ac - dc;
    }
  }

  //##############################################
  // ФМ декодирование (Оригинал)
  //##############################################
  else if (mode == FM) {
    static int16_t zi;
    ac = ((ac + i) * zi);  
    zi = i;

    static int32_t fm_smooth;
    fm_smooth = (fm_smooth * 3 + ac) / 4;  
    ac = (int16_t)fm_smooth;

  } else {
    ;  // USB, LSB, CW
  }

  //###################################################################################
  // 2. Автоматическая Регулировка Усиления (АРУ) — Защита чувствительности
  //###################################################################################
  if (agc) {                    
    if (mode == AM) {
      // Для АМ используем стандартное мягкое АРУ (process_agc), 
      // чтобы быстрое SSB-АРУ не "ослепляло" приемник при слабом сигнале!
      ac = process_agc(ac); 
    } else {
      ac = process_agc_fast(ac); // Для SSB оставляем быстрое АРУ
    }
    ac = ac >> (16 - volume);
  } else {  
    if (volume <= 13)  
      ac = ac >> (13 - volume);
    else
      ac = ac << (volume - 13);
  }

  //###################################################################################
  // 3. Шумоподавитель (NR)
  //###################################################################################
  if (nr) ac = process_nr(ac);

  //###################################################################################
  // 4. Управление цифровым фильтром (Штатный вызов без деструктивного сброса filt=0)
  //###################################################################################
  if (filt) ac = filt_var(ac);

  //###################################################################################
  // 5. Родной блок CW_DECODER (Выровнен по скобкам внутри функции)
  //###################################################################################
#ifdef CW_DECODER
  if (!(absavg256cnt % 64)) {
    _amp32 = amp32;
    amp32 = 0;
  } else {
    amp32 += abs(ac);
  }
#endif  //CW_DECODER

  // Ограничитель амплитуды ШИМ перед выходом
  ac = min(max(ac, -512), 511);

#ifdef QCX
  if (!dsp_cap) return 0;  
#endif

  return ac;
}

